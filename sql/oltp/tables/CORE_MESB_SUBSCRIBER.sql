CREATE TABLE IF NOT EXISTS CORE.CORE_MESB_SUBSCRIBER (
  MESB_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SBSB_NUM VARCHAR(30) NOT NULL UNIQUE,
  GRGR_ID BIGINT NOT NULL,
  FST_NM VARCHAR(100) NOT NULL,
  LST_NM VARCHAR(100) NOT NULL,
  DOB DATE NOT NULL,
  GNDR_CD CHAR(1),
  CRTD_TS TIMESTAMPTZ NOT NULL,
  UPDT_TS TIMESTAMPTZ NOT NULL
);
