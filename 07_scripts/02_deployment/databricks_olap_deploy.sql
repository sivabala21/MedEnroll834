-- =============================================================================
-- MedEnroll834 - Databricks OLAP (Medallion + Star Schema) DEPLOY
-- =============================================================================
-- Target catalog: med834enrl
-- Schemas: bronze, silver, gold
-- Star schema (dimensions + fact) lives in med834enrl.gold
--
-- Run on a SQL Warehouse via the Databricks SDK/CLI. Idempotent.
-- =============================================================================

-- 1. OLAP medallion schemas
CREATE SCHEMA IF NOT EXISTS med834enrl.bronze COMMENT 'OLAP bronze (raw) layer';
CREATE SCHEMA IF NOT EXISTS med834enrl.silver COMMENT 'OLAP silver (cleaned) layer';
CREATE SCHEMA IF NOT EXISTS med834enrl.gold COMMENT 'OLAP gold (star schema) layer';

-- 2. GOLD star-schema dimensions
CREATE TABLE IF NOT EXISTS med834enrl.gold.DIM_DATE (
  DATE_KEY INT NOT NULL,
  FULL_DATE DATE NOT NULL,
  YEAR_NUMBER INT NOT NULL,
  QUARTER_NUMBER INT NOT NULL,
  MONTH_NUMBER INT NOT NULL,
  DAY_NUMBER INT NOT NULL,
  DAY_OF_WEEK_NAME STRING NOT NULL
)
USING DELTA
COMMENT 'Gold date dimension. DATE_KEY uses YYYYMMDD format (e.g., 20260827 = 27-Aug-2026).';

CREATE TABLE IF NOT EXISTS med834enrl.gold.DIM_MEMBER (
  MEME_KEY BIGINT GENERATED BY DEFAULT AS IDENTITY,
  MEME_ID STRING NOT NULL,
  MESB_ID STRING NOT NULL,
  FIRST_NAME STRING NOT NULL,
  LAST_NAME STRING NOT NULL,
  DATE_OF_BIRTH DATE NOT NULL,
  GENDER_CODE STRING,
  RELATIONSHIP_CODE STRING NOT NULL,
  EFFECTIVE_DATE DATE NOT NULL,
  END_DATE DATE NOT NULL DEFAULT DATE '9999-12-31',
  CURRENT_FLAG BOOLEAN NOT NULL
)
USING DELTA
COMMENT 'Gold member dimension - SCD Type 2.';

CREATE TABLE IF NOT EXISTS med834enrl.gold.DIM_PLAN (
  PLPL_KEY BIGINT GENERATED BY DEFAULT AS IDENTITY,
  PLPL_ID STRING NOT NULL,
  PLAN_CODE STRING NOT NULL,
  PLAN_NAME STRING NOT NULL,
  LINE_OF_BUSINESS_CODE STRING NOT NULL,
  EFFECTIVE_DATE DATE NOT NULL,
  END_DATE DATE NOT NULL DEFAULT DATE '9999-12-31',
  CURRENT_FLAG BOOLEAN NOT NULL
)
USING DELTA
COMMENT 'Gold plan dimension - SCD Type 2.';

CREATE TABLE IF NOT EXISTS med834enrl.gold.DIM_GROUP (
  GRGR_KEY BIGINT GENERATED BY DEFAULT AS IDENTITY,
  GRGR_ID STRING NOT NULL,
  GROUP_NUMBER STRING NOT NULL,
  GROUP_NAME STRING NOT NULL,
  STATE_CODE STRING,
  EFFECTIVE_DATE DATE NOT NULL,
  END_DATE DATE NOT NULL DEFAULT DATE '9999-12-31',
  CURRENT_FLAG BOOLEAN NOT NULL
)
USING DELTA
COMMENT 'Gold group dimension - SCD Type 2.';

CREATE TABLE IF NOT EXISTS med834enrl.gold.DIM_TRANSACTION_SOURCE (
  TXN_SRC_KEY BIGINT GENERATED BY DEFAULT AS IDENTITY,
  TXN_ID BIGINT NOT NULL,
  FILE_NAME STRING NOT NULL,
  SENDER_ID STRING NOT NULL,
  RECEIVED_TIMESTAMP TIMESTAMP NOT NULL
)
USING DELTA
COMMENT 'Gold transaction source dimension.';

-- 3. GOLD fact table
CREATE TABLE IF NOT EXISTS med834enrl.gold.FACT_ENROLLMENT (
  ENROLLMENT_FACT_KEY BIGINT GENERATED BY DEFAULT AS IDENTITY,
  MEME_KEY BIGINT NOT NULL,
  PLPL_KEY BIGINT NOT NULL,
  GRGR_KEY BIGINT NOT NULL,
  TXN_SRC_KEY BIGINT NOT NULL,
  COVERAGE_START_DATE_KEY INT NOT NULL,
  COVERAGE_END_DATE_KEY INT NOT NULL DEFAULT 99991231,
  MAINTENANCE_TYPE_CODE STRING NOT NULL,
  ENROLLMENT_STATUS STRING NOT NULL,
  ENROLLMENT_COUNT INT NOT NULL,
  LOAD_TIMESTAMP TIMESTAMP NOT NULL
)
USING DELTA
COMMENT 'Gold enrollment fact. Grain: one row per enrollment event.';
