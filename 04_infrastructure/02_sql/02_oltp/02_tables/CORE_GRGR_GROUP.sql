CREATE TABLE IF NOT EXISTS CORE.CORE_GRGR_GROUP (
  GRGR_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  GRGR_NUM VARCHAR(20) NOT NULL UNIQUE,
  ST_CD CHAR(2) NOT NULL,
  EFF_DT DATE NOT NULL,
  TERM_DT DATE NOT NULL DEFAULT DATE '9999-12-31',
  CRTD_TS TIMESTAMPTZ NOT NULL,
  UPDT_TS TIMESTAMPTZ NOT NULL
);
