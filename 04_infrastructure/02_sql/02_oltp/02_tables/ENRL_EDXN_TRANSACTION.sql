CREATE TABLE IF NOT EXISTS ENRL.ENRL_EDXN_TRANSACTION (
  TXN_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  FILE_NM VARCHAR(255) NOT NULL,
  ISA_CTRL_NUM VARCHAR(20) NOT NULL,
  GS_CTRL_NUM VARCHAR(20) NOT NULL,
  ST_CTRL_NUM VARCHAR(20) NOT NULL,
  SNDR_ID VARCHAR(20) NOT NULL,
  RCVR_ID VARCHAR(20) NOT NULL,
  RCVD_TS TIMESTAMPTZ NOT NULL,
  PROC_STAT VARCHAR(15) NOT NULL,
  REC_CNT INTEGER
);
