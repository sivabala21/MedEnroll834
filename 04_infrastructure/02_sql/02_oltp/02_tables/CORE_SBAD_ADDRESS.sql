CREATE TABLE IF NOT EXISTS CORE.CORE_SBAD_ADDRESS (
  SBAD_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  MEME_ID BIGINT NOT NULL,
  ADR_TYP VARCHAR(10) NOT NULL,
  ADR_LN1 VARCHAR(150) NOT NULL,
  ADR_LN2 VARCHAR(150),
  CITY_NM VARCHAR(100) NOT NULL,
  ST_CD CHAR(2) NOT NULL,
  ZIP_CD VARCHAR(10) NOT NULL,
  EFF_DT DATE NOT NULL,
  CRTD_TS TIMESTAMPTZ NOT NULL
);
