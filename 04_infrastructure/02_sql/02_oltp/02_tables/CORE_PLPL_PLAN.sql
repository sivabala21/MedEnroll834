CREATE TABLE IF NOT EXISTS CORE.CORE_PLPL_PLAN (
  PLPL_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PLPL_CD VARCHAR(20) NOT NULL UNIQUE,
  PLPL_NM VARCHAR(200) NOT NULL,
  LOB_CD VARCHAR(30) NOT NULL,
  EFF_DT DATE NOT NULL,
  TERM_DT DATE NOT NULL DEFAULT DATE '9999-12-31',
  CRTD_TS TIMESTAMPTZ NOT NULL,
  UPDT_TS TIMESTAMPTZ NOT NULL
);
