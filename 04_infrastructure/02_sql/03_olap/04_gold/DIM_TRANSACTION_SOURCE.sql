CREATE TABLE IF NOT EXISTS GOLD.DIM_TRANSACTION_SOURCE (
  TXN_SRC_KEY BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TXN_ID BIGINT NOT NULL,
  FILE_NAME STRING NOT NULL,
  SENDER_ID STRING NOT NULL,
  RECEIVED_TIMESTAMP TIMESTAMP NOT NULL
)
USING DELTA
COMMENT 'Gold transaction source dimension.';
